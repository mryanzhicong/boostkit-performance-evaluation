#!/usr/bin/env python3
"""Normalize the Gradle build matrix and the upstream multi-module workload.

Every matrix scenario contributes three metrics: the median wall time of the
measured Gradle invocation (seconds, lower is better), the median build
throughput derived from that wall time (classes per second, higher is better) and
the median peak resident set size of the measuring process tree (MiB, lower is
better).  The upstream workload contributes its wall time and peak RSS.

The script reads the recorded repetitions and fails when a declared scenario is
incomplete, when a measurement exited non-zero or timed out, when a Gradle log
does not prove that the expected work happened (a clean or incremental build must
execute :compileJava, a no-op build must report it as up-to-date, the upstream
batch must build every pinned sample), or when a sampled value is not a positive
finite number.  It never fills in, estimates or zero-pads a missing measurement.
"""

from __future__ import annotations

import json
import math
import os
import re
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

SOFTWARE = "gradle"

SCALES = (100, 1000, 10000)
TASKS = ("clean_build", "incremental_build", "noop_build")
UPSTREAM_SCENARIO = "upstream_multiproject_build"
UPSTREAM_SAMPLES = (
    "platforms/documentation/docs/src/snippets/integration-tests/java/incrementalAnnotationProcessing/groovy",
    "platforms/documentation/docs/src/snippets/reference/platforms/jvm/incrementalAnnotationProcessing/groovy",
)
MATRIX_WORKLOAD = (
    "deterministic single-module Gradle java project generated by "
    "scripts/generate_project.py"
)
UPSTREAM_WORKLOAD = (
    "upstream gradle/gradle v9.8.2 source-release documentation sample projects "
    "(multi-module and composite-build layouts)"
)

COMPILE_EXECUTED = re.compile(r"^> Task :compileJava$", re.MULTILINE)
COMPILE_UP_TO_DATE = re.compile(r"^> Task :compileJava UP-TO-DATE$", re.MULTILINE)
CLEAN_EXECUTED = re.compile(r"^> Task :clean$", re.MULTILINE)
SAMPLE_HEADER = re.compile(r"^== upstream sample: (.+) ==$", re.MULTILINE)
SAMPLE_RESULT = re.compile(r"^== sample done: (.+) rc=(\d+) ==", re.MULTILINE)


def fail(message: str) -> None:
    print(f"[gradle-parse] ERROR: {message}", file=sys.stderr)


def expected_matrix_scenarios() -> list[str]:
    return [f"{task}_{scale}" for scale in SCALES for task in TASKS]


def summarize(values: list[float]) -> dict[str, float]:
    return {
        "median": round(float(statistics.median(values)), 9),
        "mean": round(float(statistics.fmean(values)), 9),
        "min": round(float(min(values)), 9),
        "max": round(float(max(values)), 9),
        "stdev": round(float(statistics.stdev(values)), 9) if len(values) > 1 else 0.0,
    }


def require_finite_positive(value: Any, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise RuntimeError(f"{label} is not numeric")
    number = float(value)
    if not math.isfinite(number) or number <= 0:
        raise RuntimeError(f"{label} must be a positive finite number")
    return number


def load_run_record(scenario_dir: Path, scenario: str, index: int) -> tuple[dict[str, Any], float, float, str]:
    sample_path = scenario_dir / f"rep{index}.json"
    if not sample_path.is_file():
        raise RuntimeError(f"missing repetition sample: {sample_path}")
    try:
        payload = json.loads(sample_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"invalid repetition sample {sample_path}: {exc}") from exc
    if not isinstance(payload, dict):
        raise RuntimeError(f"repetition sample is not an object: {sample_path}")
    if payload.get("exit_code") != 0:
        raise RuntimeError(
            f"repetition {sample_path.name} for {scenario} failed with exit code "
            f"{payload.get('exit_code')}"
        )
    if payload.get("timed_out") is True:
        raise RuntimeError(f"repetition {sample_path.name} for {scenario} timed out")
    wall_seconds = require_finite_positive(
        payload.get("wall_seconds"), f"{scenario} {sample_path.name} wall time"
    )
    rss_mib = require_finite_positive(
        payload.get("max_rss_mib"), f"{scenario} {sample_path.name} peak RSS"
    )
    log_path = scenario_dir / f"rep{index}.log"
    if not log_path.is_file() or log_path.stat().st_size == 0:
        raise RuntimeError(f"missing raw log for repetition {sample_path.name}")
    text = log_path.read_text(encoding="utf-8", errors="replace")
    return payload, wall_seconds, rss_mib, text


def check_matrix_log(scenario: str, task_label: str, index: int, log: str) -> None:
    if not log.strip():
        raise RuntimeError(f"{scenario} rep{index}: Gradle log is empty")
    if "BUILD SUCCESSFUL" not in log:
        raise RuntimeError(f"{scenario} rep{index}: Gradle log has no BUILD SUCCESSFUL")
    if "BUILD FAILED" in log:
        raise RuntimeError(f"{scenario} rep{index}: Gradle log reports BUILD FAILED")
    if task_label == "noop_build":
        if not COMPILE_UP_TO_DATE.search(log):
            raise RuntimeError(
                f"{scenario} rep{index}: no-op build did not report :compileJava as UP-TO-DATE"
            )
        if COMPILE_EXECUTED.search(log):
            raise RuntimeError(
                f"{scenario} rep{index}: no-op build unexpectedly recompiled :compileJava"
            )
        return
    if not COMPILE_EXECUTED.search(log):
        raise RuntimeError(
            f"{scenario} rep{index}: build did not execute :compileJava"
        )
    if task_label == "clean_build" and not CLEAN_EXECUTED.search(log):
        raise RuntimeError(f"{scenario} rep{index}: clean build did not execute :clean")


def matrix_metadata(scenario: str) -> dict[str, Any]:
    task, _, scale = scenario.rpartition("_")
    return {
        "scenario": scenario,
        "task": task,
        "scale_items": int(scale),
        "workload": MATRIX_WORKLOAD,
    }


def build_metric(
    name: str,
    metadata: dict[str, Any],
    value: float,
    unit: str,
    direction: str,
    statistics_payload: dict[str, float],
    samples: list[float],
) -> dict[str, Any]:
    return {
        "source_name": name,
        **metadata,
        "value": value,
        "unit": unit,
        "direction": direction,
        **statistics_payload,
        "samples": samples,
    }


def load_matrix_scenario(
    runs_dir: Path, scenario: str, reps: int
) -> tuple[list[float], list[float], list[float], dict[str, Any]]:
    metadata = matrix_metadata(scenario)
    scale = metadata["scale_items"]
    task_label = metadata["task"]
    scenario_dir = runs_dir / scenario
    if not scenario_dir.is_dir():
        raise RuntimeError(f"missing scenario directory: {scenario_dir}")
    wall_seconds: list[float] = []
    throughput: list[float] = []
    rss_mib: list[float] = []
    for index in range(1, reps + 1):
        _record, wall, rss, log = load_run_record(scenario_dir, scenario, index)
        check_matrix_log(scenario, task_label, index, log)
        if scale > 0:
            throughput.append(scale / wall)
        wall_seconds.append(wall)
        rss_mib.append(rss)
    return wall_seconds, throughput, rss_mib, metadata


def load_upstream_scenario(
    runs_dir: Path, reps: int, samples: list[str]
) -> tuple[list[float], list[float], dict[str, Any]]:
    scenario = UPSTREAM_SCENARIO
    scenario_dir = runs_dir / scenario
    if not scenario_dir.is_dir():
        raise RuntimeError(f"missing scenario directory: {scenario_dir}")
    wall: list[float] = []
    rss_mib: list[float] = []
    for index in range(1, reps + 1):
        _record, wall_seconds, rss, log = load_run_record(scenario_dir, scenario, index)
        built = {match.group(1) for match in SAMPLE_HEADER.finditer(log)}
        results = {
            match.group(1): int(match.group(2)) for match in SAMPLE_RESULT.finditer(log)
        }
        missing = [sample for sample in samples if sample not in built]
        if missing:
            raise RuntimeError(
                f"{scenario} rep{index}: upstream samples were not built: {missing}"
            )
        failed = {sample: code for sample, code in results.items() if code != 0}
        if failed:
            raise RuntimeError(f"{scenario} rep{index}: upstream sample build failed: {failed}")
        if len(built) != len(samples) or len(results) != len(samples):
            raise RuntimeError(
                f"{scenario} rep{index}: expected {len(samples)} upstream samples, "
                f"saw {len(built)} starts and {len(results)} results"
            )
        wall.append(wall_seconds)
        rss_mib.append(rss)
    metadata = {
        "scenario": scenario,
        "task": "upstream_multiproject",
        "scale_items": None,
        "upstream_samples": samples,
        "workload": UPSTREAM_WORKLOAD,
    }
    return wall, rss_mib, metadata


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: parse_benchmark.py RUNS_DIRECTORY NORMALIZED_OUTPUT", file=sys.stderr)
        return 1
    runs_dir = Path(sys.argv[1])
    normalized_output = Path(sys.argv[2])
    try:
        version = os.environ["SOFTWARE_VERSION"]
        architecture = os.environ["EXPECTED_ARCH"]
        variant = os.environ.get("PERF_VARIANT", "base")
    except KeyError as exc:
        fail(f"missing environment variable: {exc}")
        return 1
    try:
        reps = int(os.environ.get("GRADLE_REPS", "5"))
    except ValueError:
        fail("GRADLE_REPS must be an integer")
        return 1
    if reps < 1:
        fail("GRADLE_REPS must be positive")
        return 1
    if not runs_dir.is_dir():
        fail(f"runs directory does not exist: {runs_dir}")
        return 1
    samples_env = os.environ.get("GRADLE_UPSTREAM_SAMPLE_LIST", "")
    samples_list = [value for value in samples_env.splitlines() if value.strip()]
    upstream_samples = samples_list or list(UPSTREAM_SAMPLES)

    try:
        results: dict[str, Any] = {}
        for scenario in expected_matrix_scenarios():
            wall, throughput, rss_mib, metadata = load_matrix_scenario(
                runs_dir, scenario, reps
            )
            results[scenario] = build_metric(
                scenario,
                metadata,
                statistics.median(wall),
                "s",
                "lower_is_better",
                summarize(wall),
                wall,
            )
            # A no-op build deliberately compiles nothing, so a "classes per
            # second" figure would be meaningless; it only contributes wall time
            # and peak RSS.
            if metadata["task"] != "noop_build":
                results[f"{scenario}_cps"] = build_metric(
                    f"{scenario}_cps",
                    metadata,
                    statistics.median(throughput),
                    "classes/s",
                    "higher_is_better",
                    summarize(throughput),
                    throughput,
                )
            results[f"{scenario}_rss"] = build_metric(
                f"{scenario}_rss",
                metadata,
                statistics.median(rss_mib),
                "MiB",
                "lower_is_better",
                summarize(rss_mib),
                rss_mib,
            )
        wall, rss_mib, metadata = load_upstream_scenario(runs_dir, reps, upstream_samples)
        results[UPSTREAM_SCENARIO] = build_metric(
            UPSTREAM_SCENARIO,
            metadata,
            statistics.median(wall),
            "s",
            "lower_is_better",
            summarize(wall),
            wall,
        )
        results[f"{UPSTREAM_SCENARIO}_rss"] = build_metric(
            f"{UPSTREAM_SCENARIO}_rss",
            metadata,
            statistics.median(rss_mib),
            "MiB",
            "lower_is_better",
            summarize(rss_mib),
            rss_mib,
        )
    except (RuntimeError, TypeError, ValueError) as exc:
        fail(str(exc))
        return 1

    parameters = {
        "variant": variant,
        "repetitions": reps,
        "offline": True,
        "daemon": "disabled (--no-daemon, single-use daemon per invocation)",
        "max_workers": 1,
        "build_cache": "disabled",
        "gradle_version": version,
        "gradle_zip_sha256": os.environ.get("GRADLE_ZIP_SHA256", ""),
        "jdk_release": os.environ.get("GRADLE_JDK_RELEASE", ""),
        "jdk_version": os.environ.get("GRADLE_JAVA_VERSION", ""),
        "gradle_source_sha256": os.environ.get("GRADLE_SRC_SHA256", ""),
        "gradle_source_revision": os.environ.get("GRADLE_SOURCE_REVISION", f"v{version}"),
        "scales_classes": list(SCALES),
        "tasks": list(TASKS),
        "upstream_scenarios": [UPSTREAM_SCENARIO],
        "upstream_samples": upstream_samples,
    }
    payload = {
        "software": SOFTWARE,
        "version": version,
        "architecture": architecture,
        "variant": variant,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "measurement": {
            "repetitions": reps,
            "offline": True,
            "clock": "wall time around the Gradle process tree; peak RSS from getrusage(RUSAGE_CHILDREN)",
        },
        "parameters": parameters,
        "results": results,
    }
    normalized_output.parent.mkdir(parents=True, exist_ok=True)
    normalized_output.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(
        f"[gradle-parse] normalized {len(results)} metrics across "
        f"{len(expected_matrix_scenarios()) + 1} scenarios",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
