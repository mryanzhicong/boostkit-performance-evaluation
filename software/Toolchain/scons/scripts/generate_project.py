#!/usr/bin/env python3
"""Generate the fixed C source corpus and its SCons build description.

``--files`` C translation units are written to ``src/``; every unit defines one
unique function, so the project links into a static library without needing a
main program.  The ``SConstruct`` builds them into ``build/libbench.a`` with the
platform ``cc`` compiler.  No dependency resolution or network access is
involved, so the same corpus is used on both architectures of the matrix.
"""

from __future__ import annotations

import argparse
from pathlib import Path

SOURCE_TEMPLATE = """/* Generated by scripts/generate_project.py - deterministic benchmark corpus. */
#include <stdint.h>

uint64_t bench_func_{index:04d}(uint64_t input) {{
    uint64_t acc = input + {index}ULL;
    for (int i = 0; i < 64; i++) {{
        acc = (acc * 6364136223846793005ULL + 1442695040888963407ULL) % 1000000007ULL;
        if ((acc & 1ULL) == 0ULL) {{
            acc >>= 1;
        }} else {{
            acc += (uint64_t)i;
        }}
    }}
    return acc;
}}
"""

SCONSTRUCT = """# Generated by scripts/generate_project.py - deterministic benchmark project.
env = Environment(CC='cc', CCFLAGS=['-O2', '-std=c11'])
sources = sorted(Glob('src/*.c'))
env.StaticLibrary(target='build/libbench', source=sources)
"""


def write_project(output: Path, files: int) -> None:
    source_dir = output / "src"
    source_dir.mkdir(parents=True, exist_ok=True)
    for index in range(1, files + 1):
        (source_dir / f"bench_{index:04d}.c").write_text(
            SOURCE_TEMPLATE.format(index=index), encoding="utf-8"
        )
    (output / "SConstruct").write_text(SCONSTRUCT, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--files", required=True, type=int)
    args = parser.parse_args()
    if args.files <= 0:
        parser.error("--files must be positive")
    write_project(args.output, args.files)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
