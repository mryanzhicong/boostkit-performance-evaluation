#!/usr/bin/env bash
source "$(dirname "${BASH_SOURCE[0]}")/../common.sh"
source "$(dirname "${BASH_SOURCE[0]}")/base_common.sh"

ensure_source_extracted() {
    if r_container_exec test -x "${BENCH_SRC_DIR}/configure"; then
        return 0
    fi
    log_message "extracting ${BENCH_SOURCE_NAME} into ${BENCH_SRC_PARENT} inside the private container"
    r_container_exec rm -rf "${BENCH_SRC_PARENT}" "${BENCH_SRC_PARENT}.extract" || return 30
    r_container_exec mkdir -p "${BENCH_SRC_PARENT}.extract" || return 30
    extract_asset "${BENCH_DOWNLOADS_DIR}/${BENCH_SOURCE_NAME}" "${BENCH_SRC_PARENT}.extract" 1 || return 30
    r_container_exec mv "${BENCH_SRC_PARENT}.extract" "${BENCH_SRC_PARENT}" || return 30
    if ! r_container_exec test -x "${BENCH_SRC_DIR}/configure"; then
        log_message "ERROR: extracted source is missing configure: ${BENCH_SRC_DIR}"
        return 30
    fi
    return 0
}

# The configure/make/make install commands run inside the container from a small
# script written into the shared work directory: ``docker exec`` cannot feed a
# here-document to the process, and keeping the steps in a script preserves the
# exact build commands as evidence.
write_build_script() {
    local script="${BENCH_BUILD_DIR}/run-build.sh"
    cat > "${script}" <<'SCRIPT'
#!/usr/bin/env bash
# Generated by build_r_impl; runs inside the private openEuler container.
set -euo pipefail
src="$1"
install_dir="$2"
build_dir="$3"
jobs="$4"
cd "${src}"
./configure --prefix="${install_dir}" \
    --without-x --without-recommended-packages --disable-java \
    --without-readline --without-libcurl \
    > "${build_dir}/configure.log" 2>&1
make -j"${jobs}" > "${build_dir}/make.log" 2>&1
make install > "${build_dir}/install.log" 2>&1
SCRIPT
    return 0
}

# Print the tail of a container-side log file with the case log prefix.
log_tail() {
    local path="$1" lines="${2:-40}"
    r_container_exec tail -n "${lines}" "${path}" 2>/dev/null | while IFS= read -r line; do log_message "  ${line}"; done || true
}

build_r_impl() {
    prepare_r_build_container || return 30
    mkdir -p "${BENCH_DOWNLOADS_DIR}"
    materialize_asset "${BENCH_DOWNLOADS_DIR}" "${BENCH_SOURCE_NAME}" "${BENCH_SOURCE_SHA256}" \
        "${BENCH_OFFLINE_DIR}" "${BENCH_SOURCE_URLS[@]}" || return $?
    ensure_source_extracted || return $?
    r_container_exec rm -rf "${BENCH_INSTALL_DIR}" "${BENCH_BUILD_DIR}" || return 30
    r_container_exec mkdir -p "${BENCH_INSTALL_DIR}" "${BENCH_BUILD_DIR}" || return 30
    write_build_script || return 30
    log_message "configuring and building R ${SOFTWARE_VERSION} inside the private container (make -j${BENCH_BUILD_JOBS})"
    r_container_exec_env_at "${BENCH_SRC_DIR}" bash "${BENCH_BUILD_DIR}/run-build.sh" \
        "${BENCH_SRC_DIR}" "${BENCH_INSTALL_DIR}" "${BENCH_BUILD_DIR}" "${BENCH_BUILD_JOBS}" || {
        log_message "ERROR: the R build failed inside the private container"
        log_tail "${BENCH_BUILD_DIR}/configure.log"
        log_tail "${BENCH_BUILD_DIR}/make.log"
        log_tail "${BENCH_BUILD_DIR}/install.log"
        return 30
    }
    if ! r_container_exec test -x "${BENCH_BIN}"; then
        log_message "ERROR: installed Rscript binary is missing: ${BENCH_BIN}"
        return 30
    fi
    local version_line actual blas_line
    version_line="$(r_container_exec "${BENCH_R_BIN}" --version 2>&1 | head -1 || true)"
    actual="$(printf '%s' "${version_line}" | sed -n 's/^R version \([0-9][0-9.]*\).*/\1/p')"
    record_actual_version "${actual}" "${version_line}" || return 30
    blas_line="$(r_container_exec "${BENCH_BIN}" -e 'cat(extSoftVersion()["BLAS"], "\n")' 2>/dev/null || true)"
    BENCH_VERSION_LINE="${version_line}; BLAS=${blas_line}"
    log_message "R BLAS: ${blas_line}"
    BENCH_BUILD_CONFIG="$(printf '{"configure":"./configure --prefix=<install> --without-x --without-recommended-packages --disable-java --without-readline --without-libcurl","jobs":%s,"source_sha256":"%s","blas":"%s"}' \
        "${BENCH_BUILD_JOBS}" "${BENCH_SOURCE_SHA256}" "${blas_line//\"/}")"
    log_message "R build completed: ${version_line}"
}

build_config_json() {
    printf '%s\n' "${BENCH_BUILD_CONFIG}"
}

build_r_base() {
    build_r_impl || return $?
    workload_smoke || return $?
}

workload_smoke() {
    local smoke_dir="${BENCH_BUILD_DIR}/smoke"
    r_container_exec rm -rf "${smoke_dir}" || return 30
    r_container_exec mkdir -p "${smoke_dir}" || return 30
    r_container_measure_at "${smoke_dir}" "${BENCH_BIN}" "${SCRIPT_DIR}/benchmarks/bench.R" \
        crossprod_small 64 "${smoke_dir}" \
        > "${smoke_dir}/crossprod_small.log" 2>&1 || {
        log_message "ERROR: smoke workload failed; see ${smoke_dir}/crossprod_small.log"
        log_tail "${smoke_dir}/crossprod_small.log"
        return 30
    }
    if ! grep -q 'RESULT scenario=crossprod_small checksum=' "${smoke_dir}/crossprod_small.log"; then
        log_message "ERROR: smoke workload did not print a RESULT line"
        return 30
    fi
    log_message "build smoke check passed"
}
