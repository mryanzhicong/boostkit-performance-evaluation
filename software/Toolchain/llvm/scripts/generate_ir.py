#!/usr/bin/env python3
"""Generate the fixed LLVM IR corpus used by the opt/llc pipeline scenarios.

The corpus is written with opaque pointer syntax (``ptr``), which is the only
form accepted by LLVM 23, and avoids any target triple or data layout so ``llc``
uses the host triple that the case builds natively.  Every module contains
``--functions`` copies of one kernel shape plus a small dispatcher, which keeps
the measured work large enough for stable wall-clock numbers without depending on
an external compiler.
"""

from __future__ import annotations

import argparse
from pathlib import Path

ARITH_KERNEL = """define i64 @kernel_{index:04d}(i64 %n) {{
entry:
  br label %loop
loop:
  %i = phi i64 [ 0, %entry ], [ %i.next, %loop ]
  %acc = phi i64 [ {index}, %entry ], [ %acc.next, %loop ]
  %mul = mul i64 %acc, 6364136223846793005
  %add = add i64 %mul, %i
  %rem = urem i64 %add, 1000000007
  %acc.next = add i64 %rem, %acc
  %i.next = add i64 %i, 1
  %cmp = icmp ult i64 %i.next, %n
  br i1 %cmp, label %loop, label %exit
exit:
  ret i64 %acc.next
}}
"""

MEM_KERNEL = """define i64 @kernel_{index:04d}(i64 %n) {{
entry:
  %slot = alloca i64, align 8
  store i64 {index}, ptr %slot, align 8
  br label %loop
loop:
  %i = phi i64 [ 0, %entry ], [ %i.next, %loop ]
  %value = load i64, ptr %slot, align 8
  %mixed = xor i64 %value, %i
  %next = mul i64 %mixed, 6364136223846793005
  store i64 %next, ptr %slot, align 8
  %i.next = add i64 %i, 1
  %cmp = icmp ult i64 %i.next, %n
  br i1 %cmp, label %loop, label %exit
exit:
  %result = load i64, ptr %slot, align 8
  ret i64 %result
}}
"""

BRANCH_KERNEL = """define i64 @kernel_{index:04d}(i64 %n) {{
entry:
  br label %loop
loop:
  %i = phi i64 [ 0, %entry ], [ %i.next, %merge ]
  %acc = phi i64 [ {index}, %entry ], [ %acc.next, %merge ]
  %selector = and i64 %i, 3
  switch i64 %selector, label %default [
    i64 0, label %case0
    i64 1, label %case1
    i64 2, label %case2
  ]
case0:
  %c0 = add i64 %acc, %i
  br label %merge
case1:
  %c1 = sub i64 %acc, %i
  br label %merge
case2:
  %c2 = xor i64 %acc, %i
  br label %merge
default:
  %c3 = mul i64 %acc, 3
  br label %merge
merge:
  %merged = phi i64 [ %c0, %case0 ], [ %c1, %case1 ], [ %c2, %case2 ], [ %c3, %default ]
  %acc.next = add i64 %merged, %acc
  %i.next = add i64 %i, 1
  %cmp = icmp ult i64 %i.next, %n
  br i1 %cmp, label %loop, label %exit
exit:
  ret i64 %acc.next
}}
"""

KERNELS = {
    "arith": ARITH_KERNEL,
    "mem": MEM_KERNEL,
    "branch": BRANCH_KERNEL,
}

DISCLAIMER = "; Generated by scripts/generate_ir.py - deterministic benchmark corpus.\n"


def write_module(output: Path, shape: str, functions: int) -> None:
    template = KERNELS[shape]
    lines = [DISCLAIMER, "\n"]
    for index in range(1, functions + 1):
        lines.append(template.format(index=index))
        lines.append("\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--functions", required=True, type=int)
    args = parser.parse_args()
    if args.functions <= 0:
        parser.error("--functions must be positive")
    for shape in KERNELS:
        write_module(args.output_dir / f"{shape}.ll", shape, args.functions)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
