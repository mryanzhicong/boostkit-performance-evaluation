#!/usr/bin/env python3
"""Deterministically generate the Lua sources compiled by the luac scenario.

The generated tree contains ``modules`` files plus a ``main.lua`` terminal
chunk.  ``luac`` concatenates all files into one bytecode file; when the
resulting file is loaded, every concatenated chunk runs in order, so the main
chunk can aggregate the generated module functions and validate the checksum.
"""

from __future__ import annotations

import argparse
from pathlib import Path

MOD_BASE = 1009
TOTAL_MOD = 65521
HELPER_ITERATIONS = 16
TOTAL_ITERATIONS = 8
NAMES = ("alpha", "beta", "gamma", "delta", "epsilon")


def helper(x: int, index: int) -> int:
    acc = 0
    for i in range(1, HELPER_ITERATIONS + 1):
        acc = (acc + x * i + index) % MOD_BASE
    return acc


def module_buffer_length() -> int:
    parts = [f"{i}:{NAMES[i - 1]}" for i in range(1, 5)]
    return len(",".join(parts))


def module_value(index: int) -> int:
    """The value returned by generated module ``index`` at run time."""
    total = 0
    for i in range(1, TOTAL_ITERATIONS + 1):
        total += helper(i + index, index)
    for i in range(1, 6):
        total += len(NAMES[(i + index) % len(NAMES)])
    total += module_buffer_length()
    return total % TOTAL_MOD


def emit_module(directory: Path, index: int) -> None:
    name = f"module_{index:04d}"
    lines = [
        "-- generated by scripts/generate_sources.py; do not edit",
        f"local M = {index}",
        "local NAMES = {\"alpha\", \"beta\", \"gamma\", \"delta\", \"epsilon\"}",
        "",
        "local function helper(x)",
        "  local acc = 0",
        f"  for i = 1, {HELPER_ITERATIONS} do",
        "    acc = (acc + x * i + M) % 1009",
        "  end",
        "  return acc",
        "end",
        "",
        "local function pick(index)",
        "  return NAMES[index % #NAMES + 1]",
        "end",
        "",
        f"function {name}()",
        "  local total = 0",
        f"  for i = 1, {TOTAL_ITERATIONS} do",
        "    total = total + helper(i + M)",
        "  end",
        "  for i = 1, 5 do",
        "    total = total + #pick(i + M)",
        "  end",
        "  local buffer = {}",
        "  for i = 1, 4 do",
        "    buffer[i] = string.format(\"%d:%s\", i, NAMES[i])",
        "  end",
        "  total = total + #table.concat(buffer, \",\")",
        "  return total % 65521",
        "end",
        "",
        f"assert({name}() == {module_value(index)})",
        "",
    ]
    (directory / f"{name}.lua").write_text("\n".join(lines), encoding="utf-8")


def emit_main(directory: Path, modules: int) -> int:
    expected = sum(module_value(index) for index in range(1, modules + 1))
    lines = [
        "-- generated by scripts/generate_sources.py; do not edit",
        "local total = 0",
        f"for i = 1, {modules} do",
        '  local name = string.format("module_%04d", i)',
        "  total = total + _G[name]()",
        "end",
        f"assert(total == {expected}, \"generated module checksum mismatch\")",
        'print(string.format("RESULT scenario=luac_compile_%d modules=%d checksum=%d", '
        f"{modules}, {modules}, total))",
        "",
    ]
    (directory / "main.lua").write_text("\n".join(lines), encoding="utf-8")
    return expected


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--modules", required=True, type=int)
    args = parser.parse_args()
    if args.modules <= 0:
        parser.error("--modules must be positive")
    output = args.output
    output.mkdir(parents=True, exist_ok=True)
    for index in range(1, args.modules + 1):
        emit_module(output, index)
    expected = emit_main(output, args.modules)
    print(f"[generate-sources] wrote {args.modules} modules to {output}")
    print(f"[generate-sources] expected checksum: {expected}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
