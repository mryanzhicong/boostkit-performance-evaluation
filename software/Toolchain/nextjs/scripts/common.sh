nextjs_configure_container() {
    local arch
    arch="$(nextjs_normalize_arch "${EXPECTED_ARCH:-$(uname -m)}")"
    [ -n "${NEXTJS_CONTAINER_NAME}" ] || NEXTJS_CONTAINER_NAME="boostkit-nextjs-${arch}-${PERF_RUN_ID}"
    [ -n "${NEXTJS_CONTAINER_HOME}" ] || NEXTJS_CONTAINER_HOME="${PERF_WORK_DIR}/home"
