NEXTJS_IMAGE_ARCHIVE_DIR="${NEXTJS_IMAGE_ARCHIVE_DIR:-/home/runner/software/openEuler-24.03-LTS-SP4}"
NEXTJS_CA_ANCHORS_DIR="${NEXTJS_CA_ANCHORS_DIR:-/home/runner/software/anchors}"
