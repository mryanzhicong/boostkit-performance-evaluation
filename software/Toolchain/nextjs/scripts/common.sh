#!/usr/bin/env bash
# Shared configuration and helpers for the Next.js performance case.
#
# Everything in this file is deliberately architecture neutral: the parameter
# signature of a run only depends on the values recorded by
# scripts/results/parse_benchmark.py, and those must be identical on x86_64 and
# aarch64.  The Node.js archive and the native dependencies of Next.js are chosen
# per architecture but are only recorded as evidence, never as workload
# parameters.

# SCRIPT_DIR is the case root (software/Toolchain/nextjs); the shell libraries live
# in scripts/.  Every entry point therefore sources scripts/common.sh relatively.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CASE_DIR="${SCRIPT_DIR}"

# ---------------------------------------------------------------- software ---
SOFTWARE_NAME="nextjs"
CATEGORY_NAME="Toolchain"
SOFTWARE_VERSION="${SOFTWARE_VERSION:-16.4.3}"
EXPECTED_ARCH="${EXPECTED_ARCH:-x86_64}"
PERF_VARIANT="${PERF_VARIANT:-base}"

NEXT_PACKAGE="next"
NEXT_NODE_ENGINES=">=20.9.0"

# React runtime pinned by the case (the Next.js peer requirement is
# ^18.2.0 || ^19.0.0; the generated apps and the upstream example both use 19).
REACT_VERSION="19.3.1"
REACT_DOM_VERSION="19.3.1"

# TypeScript type checking of the upstream example needs these development
# dependencies; they are installed once in the shared dependency tree.
TYPESCRIPT_VERSION="5.9.3"
TYPES_NODE_VERSION="22.20.5"
TYPES_REACT_VERSION="19.3.0"
TYPES_REACT_DOM_VERSION="19.3.0"

# ---------------------------------------------------------------- runtime ----
NODE_VERSION="v22.23.4"
NODE_SEMVER="22.23.4"
NODE_SHA256_X64="1805bcd35e6815559bd2eb97db438d3fdb0eb3a5e6a977b7c1badca76337e9ce"
NODE_SHA256_ARM64="6287aa46b6c375d816e63ae66d024fbbfd70404825aabdfdf898a970871d2f4b"
NODE_DIST_BASE="https://nodejs.org/dist/${NODE_VERSION}"
NODE_TUNA_BASE="https://mirrors.tuna.tsinghua.edu.cn/nodejs-release/${NODE_VERSION}"

# Private npm registry used for the one-time dependency installation.  The Huawei
# Cloud mirror serves the tarballs directly (no redirect), which keeps the private
# cache deterministic and offline re-installs reproducible.
NPM_REGISTRY="${PERF_NPM_REGISTRY:-https://mirrors.huaweicloud.com/repository/npm}"

# Pre-placed offline assets: when this directory contains the pinned archives they
# are used and verified; otherwise the build stage downloads and verifies them.
NEXT_OFFLINE_DIR="${NEXT_OFFLINE_DIR:-/home/runner/software/nextjs}"

# Pinned Next.js release tarball (SHA-256 and the registry published SHA-512).
NEXT_TARBALL_NAME="next-${SOFTWARE_VERSION}.tgz"
NEXT_TARBALL_SHA256="d37409b7530c4873cd14c0619a7b8734777fd0dc2cae627bb592e5a82f74f8f4"
NEXT_TARBALL_SHA512_B64="OqxKTGi9u80FydydsMNYNjnuje9Au+kvHlt2GZ//ftdpDHm1dxKqAaENoOOTX5wKzn+9vaKUNIfZeyZUuLhCnA=="
NEXT_TARBALL_URL_PRIMARY="${NPM_REGISTRY}/${NEXT_PACKAGE}/-/${NEXT_TARBALL_NAME}"
NEXT_TARBALL_URL_FALLBACK="https://registry.npmjs.org/${NEXT_PACKAGE}/-/${NEXT_TARBALL_NAME}"

# Committed dependency manifest and lockfile used for the shared dependency tree.
NEXT_DEPENDENCY_MANIFEST_SHA256="7261e3a14aed6fb8ea15450d27197bf8191c7e331e3bfe8a7a650dd516770030"
NEXT_DEPENDENCY_LOCKFILE_SHA256="cbd088bbb61a97c4e293795457c2390fd0cbd190f93dfa0f20cc62bc74c2e7fd"

# --------------------------------------------------------------- measurement --
NEXT_REPS="${PERF_REPS:-5}"
NEXT_WARMUPS=1
# Next.js derives the static generation parallelism from the machine's CPU count.
# That would make the same workload behave differently on two runners, so every
# generated app pins experimental.cpus=2 (recorded as a workload parameter).
NEXT_BUILD_WORKERS=2
# Serial loopback request matrix (the delivery load: 100 GET requests plus a
# content verification of the last item page).
NEXT_HTTP_REQUESTS=100
NEXT_HTTP_PORT="${PERF_NEXT_HTTP_PORT:-18181}"
NEXT_HTTP_HOST="127.0.0.1"

# Static page counts of the generated apps (one route with generateStaticParams).
NEXT_STATIC_SMALL_ITEMS=1000
NEXT_STATIC_LARGE_ITEMS=3000
NEXT_DYNAMIC_ROUTES=500
NEXT_FILE_ROUTES=500

# Deterministic apps generated by scripts/fixtures/generate_projects.py.
NEXT_GENERATED_PROJECTS=(static_1000 static_3000 dynamic_500 routes_500)
# Every project that appears in a scenario (upstream is copied from the fixture).
NEXT_PROJECTS=(static_1000 static_3000 dynamic_500 routes_500 upstream)

# Scenario execution order.  The authoritative description of every scenario
# (project, command, expected counts, correctness bounds) lives in the metadata
# file written by the build stage and is read by the parser; this list only drives
# execution.
NEXT_SCENARIOS=(
    build_static_1000
    build_static_3000
    build_dynamic_500
    build_routes_500
    build_incremental_1000
    build_upstream
    serve_startup_1000
    serve_get_100_static
    serve_get_100_dynamic
)

log_message() {
    printf '[nextjs] [%s] %s\n' "$(date -u '+%Y-%m-%d %H:%M:%S')" "$*"
}

fail_message() {
    printf '[nextjs] [%s] ERROR: %s\n' "$(date -u '+%Y-%m-%d %H:%M:%S')" "$*" >&2
}

normalize_architecture() {
    case "${EXPECTED_ARCH}" in
        x86_64|amd64) printf 'x86_64\n' ;;
        aarch64|arm64) printf 'aarch64\n' ;;
        *) return 1 ;;
    esac
}

validate_variant() {
    case "${PERF_VARIANT}" in
        base|optimized) return 0 ;;
        *)
            fail_message "unsupported variant: ${PERF_VARIANT} (expected base or optimized)"
            return 10
            ;;
    esac
}

validate_reps() {
    if ! [[ "${NEXT_REPS}" =~ ^[0-9]+$ ]] || [[ "${NEXT_REPS}" -lt 1 ]]; then
        fail_message "PERF_REPS must be a positive integer, got: ${NEXT_REPS}"
        return 10
    fi
    if [[ "${NEXT_REPS}" -gt 50 ]]; then
        fail_message "PERF_REPS is unreasonably large: ${NEXT_REPS}"
        return 10
    fi
}

select_node_artifact() {
    local arch="$1"
    case "${arch}" in
        x86_64)
            NODE_PLATFORM="linux-x64"
            NODE_TARBALL_NAME="node-${NODE_VERSION}-linux-x64.tar.xz"
            NODE_SHA256="${NODE_SHA256_X64}"
            ;;
        aarch64)
            NODE_PLATFORM="linux-arm64"
            NODE_TARBALL_NAME="node-${NODE_VERSION}-linux-arm64.tar.xz"
            NODE_SHA256="${NODE_SHA256_ARM64}"
            ;;
        *)
            fail_message "unsupported architecture: ${arch}"
            return 10
            ;;
    esac
    NODE_TARBALL_URLS=(
        "${NEXT_OFFLINE_DIR}/${NODE_TARBALL_NAME}"
        "${NODE_TUNA_BASE}/${NODE_TARBALL_NAME}"
        "${NODE_DIST_BASE}/${NODE_TARBALL_NAME}"
    )
}

# The native dependency of Next.js is selected by npm from the committed lockfile
# according to cpu/libc; it is reported as per-metric evidence by the parser and
# never as a workload parameter.
select_swc_backend() {
    local arch="$1"
    case "${arch}" in
        x86_64) SWC_PACKAGE="@next/swc-linux-x64-gnu" ;;
        aarch64) SWC_PACKAGE="@next/swc-linux-arm64-gnu" ;;
        *)
            fail_message "unsupported architecture: ${arch}"
            return 10
            ;;
    esac
}

scenario_project() {
    case "$1" in
        build_static_1000|build_incremental_1000|serve_startup_1000|serve_get_100_static)
            printf 'static_1000\n'
            ;;
        build_static_3000|serve_get_100_static_large) printf 'static_3000\n' ;;
        build_dynamic_500|serve_get_100_dynamic) printf 'dynamic_500\n' ;;
        build_routes_500) printf 'routes_500\n' ;;
        build_upstream) printf 'upstream\n' ;;
        *) return 1 ;;
    esac
}

scenario_kind() {
    case "$1" in
        serve_*) printf 'http\n' ;;
        build_*) printf 'build\n' ;;
        *) return 1 ;;
    esac
}

scenario_command_text() {
    case "$1" in
        serve_startup_1000) printf 'next start + first loopback GET / (startup latency)\n' ;;
        serve_get_100_static) printf 'next start + %s serial loopback GET /items/item-999\n' "${NEXT_HTTP_REQUESTS}" ;;
        serve_get_100_dynamic) printf 'next start + %s serial loopback GET /dyn/item-42\n' "${NEXT_HTTP_REQUESTS}" ;;
        build_*) printf 'next build\n' ;;
        *) return 1 ;;
    esac
}

configure_runtime_paths() {
    local arch
    arch="$(normalize_architecture)" || {
        fail_message "unsupported architecture: ${EXPECTED_ARCH}"
        return 10
    }
    EXPECTED_ARCH="${arch}"
    select_node_artifact "${arch}" || return $?
    select_swc_backend "${arch}" || return $?

    RESULTS_DIR="${RESULTS_DIR:-${CASE_DIR}/results}"
    PERF_RUN_ID="${PERF_RUN_ID:-local-$(date -u '+%Y%m%dT%H%M%SZ')-$$}"
    if [[ -z "${PERF_WORK_DIR:-}" ]]; then
        # Standalone entry point: keep the work directory clearly marked as local so
        # that a copy of the case outside the repository can clean up only its own
        # directory.  The framework always provides PERF_WORK_DIR.
        PERF_WORK_DIR="/home/runner/boostkit-perf/${SOFTWARE_NAME}/local-${PERF_RUN_ID}"
        STANDALONE_OWNS_WORK_DIR=1
    fi
    PERF_ACTUAL_VERSION_FILE="${PERF_ACTUAL_VERSION_FILE:-${RESULTS_DIR}/actual-version.txt}"

    RUNS_DIR="${RESULTS_DIR}/runs"
    NODE_INSTALL_DIR="${PERF_WORK_DIR}/node-install"
    NODE_BIN="${NODE_INSTALL_DIR}/bin/node"
    NPM_CLI="${NODE_INSTALL_DIR}/lib/node_modules/npm/bin/npm-cli.js"
    # The shared dependency tree lives in the work directory root so that Node.js
    # resolves next/react/react-dom/typescript from every project below projects/.
    DEPS_DIR="${PERF_WORK_DIR}"
    NODE_MODULES_DIR="${PERF_WORK_DIR}/node_modules"
    NPM_CACHE_DIR="${PERF_WORK_DIR}/npm-cache"
    PROJECTS_DIR="${PERF_WORK_DIR}/projects"
    TEMPLATES_DIR="${PERF_WORK_DIR}/project-templates"
    NEXT_BIN="${NODE_MODULES_DIR}/next/dist/bin/next"
    NEXT_INSTALL_DIR="${NODE_MODULES_DIR}/next"
    NEXT_FIXTURE_METADATA="${PERF_WORK_DIR}/fixtures-metadata.json"
    NEXT_PRIVATE_HOME="${PERF_WORK_DIR}/home"
    # Turbopack workspace root: the dependency tree is shared above the projects,
    # so the work directory must be the workspace root or Turbopack refuses to
    # resolve Next.js from outside the app directory.
    NEXT_TURBOPACK_ROOT="${PERF_WORK_DIR}"

    export SOFTWARE_VERSION EXPECTED_ARCH PERF_VARIANT PERF_RUN_ID RESULTS_DIR RUNS_DIR
    export PERF_WORK_DIR PERF_ACTUAL_VERSION_FILE NODE_INSTALL_DIR NODE_BIN NPM_CLI
    export DEPS_DIR NODE_MODULES_DIR NPM_CACHE_DIR PROJECTS_DIR TEMPLATES_DIR
    export NEXT_BIN NEXT_INSTALL_DIR NEXT_FIXTURE_METADATA NEXT_PRIVATE_HOME NEXT_TURBOPACK_ROOT
    export NEXT_REPS NEXT_WARMUPS NEXT_BUILD_WORKERS NEXT_HTTP_REQUESTS STANDALONE_OWNS_WORK_DIR
    export NEXT_HTTP_PORT NEXT_HTTP_HOST
    export NODE_PLATFORM NODE_TARBALL_NAME NODE_SHA256 NPM_REGISTRY NEXT_OFFLINE_DIR
    export NEXT_TARBALL_NAME NEXT_TARBALL_SHA256 NEXT_TARBALL_SHA512_B64
    export NEXT_TARBALL_URL_PRIMARY NEXT_TARBALL_URL_FALLBACK
    export NEXT_STATIC_SMALL_ITEMS NEXT_STATIC_LARGE_ITEMS NEXT_DYNAMIC_ROUTES NEXT_FILE_ROUTES
    export NEXT_NODE_ENGINES REACT_VERSION REACT_DOM_VERSION
    export TYPESCRIPT_VERSION TYPES_NODE_VERSION TYPES_REACT_VERSION TYPES_REACT_DOM_VERSION
    export NEXT_DEPENDENCY_MANIFEST_SHA256 NEXT_DEPENDENCY_LOCKFILE_SHA256
    export NODE_SEMVER NODE_VERSION SWC_PACKAGE
    return 0
}

initialize_runtime() {
    configure_runtime_paths || return $?
    mkdir -p "${RESULTS_DIR}" "${RUNS_DIR}" "${PERF_WORK_DIR}" "${NPM_CACHE_DIR}" \
        "${PROJECTS_DIR}" "${TEMPLATES_DIR}" "${NEXT_PRIVATE_HOME}" || {
        fail_message "failed to create the work directories under ${PERF_WORK_DIR}"
        return 20
    }
    return 0
}

# Count the source files of a project tree, ignoring build output and installed
# dependencies.  The parser compares this against the build stage record, so a
# measured run that silently compiled the wrong tree is rejected.
count_project_sources() {
    local directory="$1"
    find "${directory}" -type f \
        \( -name '*.js' -o -name '*.jsx' -o -name '*.ts' -o -name '*.tsx' -o -name '*.mjs' -o -name '*.json' \) \
        -not -path '*/node_modules/*' -not -path '*/.next/*' -not -path '*/.next-cold/*' \
        -not -path '*/.git/*' -not -name 'next-env.d.ts' 2>/dev/null | wc -l
}

count_static_pages() {
    local directory="$1"
    find "${directory}" -name '*.html' 2>/dev/null | wc -l
}

copy_project_template() {
    local project="$1"
    local target="${PROJECTS_DIR}/${project}"
    if [[ ! -d "${TEMPLATES_DIR}/${project}" ]]; then
        fail_message "missing project template: ${TEMPLATES_DIR}/${project}"
        return 20
    fi
    rm -rf -- "${target}"
    mkdir -p "${target}"
    if ! cp -a "${TEMPLATES_DIR}/${project}/." "${target}/"; then
        fail_message "failed to copy the project template for ${project}"
        return 20
    fi
    return 0
}

remove_project_output() {
    local project="$1"
    rm -rf -- "${PROJECTS_DIR}/${project}/.next" "${PROJECTS_DIR}/${project}/.next-cold"
    return 0
}
