log_message() {
    printf '[nextjs] [%s] %s\n' "$(date -u '+%Y-%m-%d %H:%M:%S')" "$*"
}

fail_message() {
    printf '[nextjs] [%s] ERROR: %s\n' "$(date -u '+%Y-%m-%d %H:%M:%S')" "$*" >&2
}

normalize_architecture() {
    case "${EXPECTED_ARCH}" in
        x86_64|amd64) printf 'x86_64\n' ;;
        aarch64|arm64) printf 'aarch64\n' ;;
        *) return 1 ;;
    esac
}

validate_variant() {
    case "${PERF_VARIANT}" in
        base|optimized) return 0 ;;
        *)
            fail_message "unsupported variant: ${PERF_VARIANT} (expected base or optimized)"
            return 10
            ;;
    esac
}

validate_reps() {
    if ! [[ "${NEXT_REPS}" =~ ^[0-9]+$ ]] || [[ "${NEXT_REPS}" -lt 1 ]]; then
        fail_message "PERF_REPS must be a positive integer, got: ${NEXT_REPS}"
        return 10
    fi
    if [[ "${NEXT_REPS}" -gt 50 ]]; then
        fail_message "PERF_REPS is unreasonably large: ${NEXT_REPS}"
        return 10
    fi
}

select_node_artifact() {
    local arch="$1"
    case "${arch}" in
        x86_64)
            NODE_PLATFORM="linux-x64"
            NODE_TARBALL_NAME="node-${NODE_VERSION}-linux-x64.tar.xz"
            NODE_SHA256="${NODE_SHA256_X64}"
            ;;
        aarch64)
            NODE_PLATFORM="linux-arm64"
            NODE_TARBALL_NAME="node-${NODE_VERSION}-linux-arm64.tar.xz"
            NODE_SHA256="${NODE_SHA256_ARM64}"
            ;;
        *)
            fail_message "unsupported architecture: ${arch}"
            return 10
            ;;
    esac
    NODE_TARBALL_URLS=(
        "${NEXT_OFFLINE_DIR}/${NODE_TARBALL_NAME}"
        "${NODE_TUNA_BASE}/${NODE_TARBALL_NAME}"
        "${NODE_DIST_BASE}/${NODE_TARBALL_NAME}"
    )
}

# The native dependency of Next.js is selected by npm from the committed lockfile
# according to cpu/libc; it is reported as per-metric evidence by the parser and
# never as a workload parameter.
select_swc_backend() {
    local arch="$1"
    case "${arch}" in
        x86_64) SWC_PACKAGE="@next/swc-linux-x64-gnu" ;;
        aarch64) SWC_PACKAGE="@next/swc-linux-arm64-gnu" ;;
        *)
            fail_message "unsupported architecture: ${arch}"
            return 10
            ;;
    esac
}

scenario_project() {
    case "$1" in
        build_static_1000|build_incremental_1000|serve_startup_1000|serve_get_100_static)
            printf 'static_1000\n'
            ;;
