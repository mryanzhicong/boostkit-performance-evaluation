configure_runtime_paths() {
    local arch
    arch="$(normalize_architecture)" || {
        fail_message "unsupported architecture: ${EXPECTED_ARCH}"
        return 10
    }
    EXPECTED_ARCH="${arch}"
    select_node_artifact "${arch}" || return $?
    select_swc_backend "${arch}" || return $?

    RESULTS_DIR="${RESULTS_DIR:-${CASE_DIR}/results}"
    PERF_RUN_ID="${PERF_RUN_ID:-local-$(date -u '+%Y%m%dT%H%M%SZ')-$$}"
    if [[ -z "${PERF_WORK_DIR:-}" ]]; then
        # Standalone entry point: keep the work directory clearly marked as local so
        # that a copy of the case outside the repository can clean up only its own
        # directory.  The framework always provides PERF_WORK_DIR.
        PERF_WORK_DIR="/home/runner/boostkit-perf/${SOFTWARE_NAME}/local-${PERF_RUN_ID}"
        STANDALONE_OWNS_WORK_DIR=1
    fi
    PERF_ACTUAL_VERSION_FILE="${PERF_ACTUAL_VERSION_FILE:-${RESULTS_DIR}/actual-version.txt}"

    RUNS_DIR="${RESULTS_DIR}/runs"
    NODE_INSTALL_DIR="${PERF_WORK_DIR}/node-install"
    NODE_BIN="${NODE_INSTALL_DIR}/bin/node"
    NPM_CLI="${NODE_INSTALL_DIR}/lib/node_modules/npm/bin/npm-cli.js"
    # The shared dependency tree lives in the work directory root so that Node.js
    # resolves next/react/react-dom/typescript from every project below projects/.
    DEPS_DIR="${PERF_WORK_DIR}"
    NODE_MODULES_DIR="${PERF_WORK_DIR}/node_modules"
    NPM_CACHE_DIR="${PERF_WORK_DIR}/npm-cache"
    PROJECTS_DIR="${PERF_WORK_DIR}/projects"
    TEMPLATES_DIR="${PERF_WORK_DIR}/project-templates"
    NEXT_BIN="${NODE_MODULES_DIR}/next/dist/bin/next"
    NEXT_INSTALL_DIR="${NODE_MODULES_DIR}/next"
    NEXT_FIXTURE_METADATA="${PERF_WORK_DIR}/fixtures-metadata.json"
    NEXT_PRIVATE_HOME="${PERF_WORK_DIR}/home"
    # Turbopack workspace root: the dependency tree is shared above the projects,
    # so the work directory must be the workspace root or Turbopack refuses to
    # resolve Next.js from outside the app directory.
    NEXT_TURBOPACK_ROOT="${PERF_WORK_DIR}"

    export SOFTWARE_VERSION EXPECTED_ARCH PERF_VARIANT PERF_RUN_ID RESULTS_DIR RUNS_DIR
    export PERF_WORK_DIR PERF_ACTUAL_VERSION_FILE NODE_INSTALL_DIR NODE_BIN NPM_CLI
    export DEPS_DIR NODE_MODULES_DIR NPM_CACHE_DIR PROJECTS_DIR TEMPLATES_DIR
    export NEXT_BIN NEXT_INSTALL_DIR NEXT_FIXTURE_METADATA NEXT_PRIVATE_HOME NEXT_TURBOPACK_ROOT
    export NEXT_REPS NEXT_WARMUPS NEXT_BUILD_WORKERS NEXT_HTTP_REQUESTS STANDALONE_OWNS_WORK_DIR
    export NEXT_HTTP_PORT NEXT_HTTP_HOST
    export NODE_PLATFORM NODE_TARBALL_NAME NODE_SHA256 NPM_REGISTRY NEXT_OFFLINE_DIR
    export NEXT_TARBALL_NAME NEXT_TARBALL_SHA256 NEXT_TARBALL_SHA512_B64
    export NEXT_TARBALL_URL_PRIMARY NEXT_TARBALL_URL_FALLBACK
    export NEXT_STATIC_SMALL_ITEMS NEXT_STATIC_LARGE_ITEMS NEXT_DYNAMIC_ROUTES NEXT_FILE_ROUTES
    export NEXT_NODE_ENGINES REACT_VERSION REACT_DOM_VERSION
    export TYPESCRIPT_VERSION TYPES_NODE_VERSION TYPES_REACT_VERSION TYPES_REACT_DOM_VERSION
    export NEXT_DEPENDENCY_MANIFEST_SHA256 NEXT_DEPENDENCY_LOCKFILE_SHA256
    export NODE_SEMVER NODE_VERSION SWC_PACKAGE
    return 0
}

initialize_runtime() {
    configure_runtime_paths || return $?
    mkdir -p "${RESULTS_DIR}" "${RUNS_DIR}" "${PERF_WORK_DIR}" "${NPM_CACHE_DIR}" \
        "${PROJECTS_DIR}" "${TEMPLATES_DIR}" "${NEXT_PRIVATE_HOME}" || {
        fail_message "failed to create the work directories under ${PERF_WORK_DIR}"
        return 20
    }
    return 0
}

# Count the source files of a project tree, ignoring build output and installed
# dependencies.  The parser compares this against the build stage record, so a
# measured run that silently compiled the wrong tree is rejected.
count_project_sources() {
    local directory="$1"
    find "${directory}" -type f \
        \( -name '*.js' -o -name '*.jsx' -o -name '*.ts' -o -name '*.tsx' -o -name '*.mjs' -o -name '*.json' \) \
        -not -path '*/node_modules/*' -not -path '*/.next/*' -not -path '*/.next-cold/*' \
        -not -path '*/.git/*' -not -name 'next-env.d.ts' 2>/dev/null | wc -l
}

count_static_pages() {
    local directory="$1"
    find "${directory}" -name '*.html' 2>/dev/null | wc -l
}

copy_project_template() {
    local project="$1"
    local target="${PROJECTS_DIR}/${project}"
    if [[ ! -d "${TEMPLATES_DIR}/${project}" ]]; then
        fail_message "missing project template: ${TEMPLATES_DIR}/${project}"
        return 20
    fi
    rm -rf -- "${target}"
    mkdir -p "${target}"
    if ! cp -a "${TEMPLATES_DIR}/${project}/." "${target}/"; then
        fail_message "failed to copy the project template for ${project}"
        return 20
    fi
    return 0
}

remove_project_output() {
    local project="$1"
    rm -rf -- "${PROJECTS_DIR}/${project}/.next" "${PROJECTS_DIR}/${project}/.next-cold"
    return 0
}

