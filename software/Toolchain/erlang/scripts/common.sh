ERLANG_IMAGE_ARCHIVE_DIR="${ERLANG_IMAGE_ARCHIVE_DIR:-/home/runner/software/openEuler-24.03-LTS-SP4}"
ERLANG_CA_ANCHORS_DIR="${ERLANG_CA_ANCHORS_DIR:-/home/runner/software/anchors}"
