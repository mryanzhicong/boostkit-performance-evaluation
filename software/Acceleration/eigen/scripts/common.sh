#!/usr/bin/env bash
# Shared state and helpers for the Eigen Acceleration performance case.
#
# Eigen is a header-only C++ library, so the measured workload is the benchmark
# suite that ships inside the pinned upstream archive: bench/btl (BTL) built with
# the upstream option -DEIGEN_BUILD_BTL=ON.  See README.md for why that entry was
# chosen and why bench/spbench is not used.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOFTWARE_NAME="eigen"
SOFTWARE_VERSION="${SOFTWARE_VERSION:-5.0.1}"
EXPECTED_ARCH="${EXPECTED_ARCH:-$(uname -m)}"
PERF_VARIANT="${PERF_VARIANT:-base}"
PERF_RUN_ID="${PERF_RUN_ID:-}"
RESULTS_DIR="${RESULTS_DIR:-}"
PERF_WORK_DIR="${PERF_WORK_DIR:-}"
PERF_ACTUAL_VERSION_FILE="${PERF_ACTUAL_VERSION_FILE:-}"

# Upstream release artifact.  The archive is the tag archive generated by the
# upstream GitLab project; the digest below was computed from the downloaded
# file and is the only accepted input on every architecture and every mirror.
EIGEN_UPSTREAM_PROJECT="https://gitlab.com/libeigen/eigen"
EIGEN_RELEASE_BASE="${EIGEN_UPSTREAM_PROJECT}/-/archive"
EIGEN_ARCHIVE_NAME="eigen-${SOFTWARE_VERSION}.tar.gz"
EIGEN_ARCHIVE_SHA256="e9c326dc8c05cd1e044c71f30f1b2e34a6161a3b6ecf445d56b53ff1669e3dec"
EIGEN_ARCHIVE_URL="${EIGEN_RELEASE_BASE}/${SOFTWARE_VERSION}/${EIGEN_ARCHIVE_NAME}"

# Pre-placed offline mirrors are the preferred input; the directory is read-only
# for the case.  PERF_EIGEN_ARCHIVE_URL pins one complete URL and
# PERF_EIGEN_MIRROR prefixes the pinned archive name for restricted networks.
EIGEN_OFFLINE_DIR="${PERF_EIGEN_OFFLINE_DIR:-/home/runner/software/eigen}"
PERF_EIGEN_ARCHIVE_URL="${PERF_EIGEN_ARCHIVE_URL:-}"
PERF_EIGEN_MIRROR="${PERF_EIGEN_MIRROR:-}"
# Public forwarding proxy kept as a last resort for networks that cannot reach
# gitlab.com directly.  It must still return the byte-identical archive.
EIGEN_PROXY_PREFIX="${PERF_EIGEN_PROXY_PREFIX:-https://gh-proxy.com/}"

# The measured matrix.  A scenario is one upstream BTL executable limited to one
# BTL action with BTL_CONFIG; each run performs the upstream size sweep, so the
# GFLOPS of several matrix dimensions are read from a single, unmodified run.
EIGEN_GROUPS=(o3 native)
EIGEN_ACTIONS=(gemm gemv trisolve_matrix cholesky axpy)
EIGEN_SCALES=(128 512 1024)
# Action -> (upstream BTL executable, BTL_CONFIG action selector).
EIGEN_BTL_CONFIG="-t 1 --overwrite"
EIGEN_BTL_NB_POINT=100
EIGEN_BTL_MIN_TIME="0.2"

EIGEN_REPS="${PERF_REPS:-5}"
EIGEN_JOBS="${PERF_EIGEN_JOBS:-6}"
EIGEN_RUN_TIMEOUT="${PERF_EIGEN_RUN_TIMEOUT:-1800}"

# Lifecycle paths (assigned in configure_runtime_paths).
SOURCE_ARCHIVE=""
SOURCE_DIR=""
BUILD_ROOT=""
PROBE_DIR=""
SCRATCH_DIR=""
NATIVE_FLAG_FILE=""
RUNS_DIR=""
EIGEN_NATIVE_FLAG=""
COMPILER_IDENTITY="${COMPILER_IDENTITY:-}"
CMAKE_IDENTITY="${CMAKE_IDENTITY:-}"

STANDALONE_OWNS_WORK_DIR="${STANDALONE_OWNS_WORK_DIR:-0}"
STANDALONE_KEEP_WORK_DIR="${STANDALONE_KEEP_WORK_DIR:-0}"
STANDALONE_STOP_DONE="${STANDALONE_STOP_DONE:-0}"
STANDALONE_CLEANUP_DONE="${STANDALONE_CLEANUP_DONE:-0}"

log_message() {
    printf '[eigen] [%s] %s\n' "$(TZ=UTC-8 date '+%F %T')" "$*"
}

normalize_architecture() {
    case "${1,,}" in
        x86_64|amd64) printf 'x86_64\n' ;;
        aarch64|arm64) printf 'aarch64\n' ;;
        *) printf '%s\n' "${1,,}" ;;
    esac
}

# Version string of the extracted upstream headers ("Eigen/Version").  This is
# the product's own version, not the requested one.
source_version_string() {
    local version_file="${SOURCE_DIR}/Eigen/Version"
    [[ -f "${version_file}" ]] || return 1
    sed -n 's/^#define EIGEN_VERSION_STRING "\(.*\)"$/\1/p' "${version_file}" | head -n 1
}

validate_variant() {
    case "${PERF_VARIANT}" in
        base|optimized) ;;
        *) log_message "ERROR: invalid build variant: ${PERF_VARIANT}"; return 10 ;;
    esac
}

validate_reps() {
    [[ "${EIGEN_REPS}" =~ ^[1-9][0-9]*$ ]] || {
        log_message "ERROR: PERF_REPS must be a positive integer, got ${EIGEN_REPS}"
        return 10
    }
    if ((EIGEN_REPS < 5)); then
        log_message "WARNING: PERF_REPS=${EIGEN_REPS} is a local link-validation value; formal evidence requires >= 5"
    fi
}

validate_jobs() {
    [[ "${EIGEN_JOBS}" =~ ^[1-9][0-9]*$ ]] || {
        log_message "ERROR: PERF_EIGEN_JOBS must be a positive integer, got ${EIGEN_JOBS}"
        return 10
    }
    if ((EIGEN_JOBS > 256)); then
        log_message "ERROR: PERF_EIGEN_JOBS is unreasonably large: ${EIGEN_JOBS}"
        return 10
    fi
}

action_binary() {
    case "$1" in
        gemm) printf 'btl_eigen3_matmat\n' ;;
        gemv) printf 'btl_eigen3_vecmat\n' ;;
        trisolve_matrix|cholesky) printf 'btl_eigen3_adv\n' ;;
        axpy) printf 'btl_eigen3_linear\n' ;;
        *) printf 'unknown\n' ;;
    esac
}

action_filter() {
    case "$1" in
        gemm) printf 'matrix_matrix\n' ;;
        gemv) printf 'matrix_vector\n' ;;
        trisolve_matrix) printf 'trisolve_matrix\n' ;;
        cholesky) printf 'cholesky\n' ;;
        axpy) printf 'axpy\n' ;;
        *) printf 'unknown\n' ;;
    esac
}

action_workload() {
    case "$1" in
        gemm) printf 'dense matrix-matrix product (BTL matrix_matrix)\n' ;;
        gemv) printf 'dense matrix-vector product (BTL matrix_vector)\n' ;;
        trisolve_matrix) printf 'dense triangular solve with matrix right-hand side (BTL trisolve_matrix)\n' ;;
        cholesky) printf 'dense Cholesky factorization (BTL cholesky)\n' ;;
        axpy) printf 'BLAS-1 scaled vector addition (BTL axpy)\n' ;;
        *) printf 'unknown\n' ;;
    esac
}

btl_binary_path() {
    local group="$1" action="$2"
    printf '%s/%s/bench/btl/libs/eigen3/%s\n' \
        "${BUILD_ROOT}" "${group}" "$(action_binary "${action}")"
}

# Fixed-dimension driver compiled from the upstream BTL action headers.  It is
# used only for the per-dimension GFLOPS metrics, because the upstream sweep
# times a single size and derives the remaining curve from that one measurement
# (see scripts/btl_single_point.cpp).
single_point_binary_path() {
    printf '%s/btl_single_point_%s\n' "${PROBE_DIR}" "$1"
}

scenario_list() {
    local group action
    for group in "${EIGEN_GROUPS[@]}"; do
        for action in "${EIGEN_ACTIONS[@]}"; do
            printf '%s_%s\n' "${group}" "${action}"
        done
    done
}

# "-O3" group keeps the flags the upstream BTL CMakeLists sets for GCC
# ("-g0 -O3 -DNDEBUG"); no extra flag is appended.  The vectorised group adds the
# architecture native instruction-set flag, which is resolved once in the build
# stage (and persisted) because aarch64 compilers differ in what they accept.
native_group_flag() {
    case "${EXPECTED_ARCH}" in
        x86_64) printf -- '-march=native\n' ;;
        aarch64) printf -- '%s\n' "${EIGEN_NATIVE_FLAG:-}" ;;
        *) printf '\n' ;;
    esac
}

group_cxx_flags() {
    case "$1" in
        o3) printf '\n' ;;
        native) native_group_flag ;;
        *) printf '\n' ;;
    esac
}

configure_runtime_paths() {
    validate_variant || return $?
    validate_reps || return $?
    validate_jobs || return $?
    if [[ -z "${PERF_RUN_ID}" ]]; then
        PERF_RUN_ID="local-$(date -u '+%Y%m%dT%H%M%SZ')-$$"
    fi
    if [[ ! "${PERF_RUN_ID}" =~ ^[A-Za-z0-9._-]+$ ]]; then
        log_message "ERROR: PERF_RUN_ID contains unsafe characters: ${PERF_RUN_ID}"
        return 10
    fi
    case "${EXPECTED_ARCH,,}" in
        x86_64|amd64) EXPECTED_ARCH="x86_64" ;;
        aarch64|arm64) EXPECTED_ARCH="aarch64" ;;
        *)
            log_message "ERROR: unsupported expected architecture: ${EXPECTED_ARCH}"
            return 20
            ;;
    esac
    local runner_architecture
    runner_architecture="$(normalize_architecture "$(uname -m)")"
    case "${runner_architecture}" in
        x86_64|aarch64) ;;
        *)
            log_message "ERROR: unsupported runner architecture: $(uname -m)"
            return 20
            ;;
    esac
    if [[ "${runner_architecture}" != "${EXPECTED_ARCH}" ]]; then
        log_message "ERROR: expected architecture ${EXPECTED_ARCH}, runner is ${runner_architecture}"
        return 20
    fi
    if [[ -z "${RESULTS_DIR}" ]]; then
        if [[ "${PERF_VARIANT}" == optimized ]]; then
            RESULTS_DIR="${SCRIPT_DIR}/results/${SOFTWARE_VERSION}/optimized/${PERF_RUN_ID}"
        else
            RESULTS_DIR="${SCRIPT_DIR}/results/${SOFTWARE_VERSION}/${PERF_RUN_ID}"
        fi
    fi
    if [[ -z "${PERF_WORK_DIR}" ]]; then
        PERF_WORK_DIR="/home/runner/boostkit-perf/eigen/local-${PERF_RUN_ID}"
        STANDALONE_OWNS_WORK_DIR=1
    fi
    TMPDIR="${PERF_WORK_DIR}/tmp"
    if [[ -z "${PERF_ACTUAL_VERSION_FILE}" ]]; then
        PERF_ACTUAL_VERSION_FILE="${RESULTS_DIR}/actual-version.txt"
    fi
    SOURCE_ARCHIVE="${PERF_WORK_DIR}/downloads/${EIGEN_ARCHIVE_NAME}"
    SOURCE_DIR="${PERF_WORK_DIR}/eigen-source"
    BUILD_ROOT="${PERF_WORK_DIR}/build"
    PROBE_DIR="${PERF_WORK_DIR}/probe"
    SCRATCH_DIR="${PERF_WORK_DIR}/scratch"
    NATIVE_FLAG_FILE="${PERF_WORK_DIR}/native-flag.txt"
    RUNS_DIR="${RESULTS_DIR}/runs"
    EIGEN_NATIVE_FLAG=""
    if [[ -f "${NATIVE_FLAG_FILE}" ]]; then
        EIGEN_NATIVE_FLAG="$(< "${NATIVE_FLAG_FILE}")"
    fi
    export SOFTWARE_NAME SOFTWARE_VERSION EXPECTED_ARCH PERF_VARIANT PERF_RUN_ID
    export RESULTS_DIR PERF_WORK_DIR PERF_ACTUAL_VERSION_FILE TMPDIR
    export SOURCE_ARCHIVE SOURCE_DIR BUILD_ROOT PROBE_DIR SCRATCH_DIR RUNS_DIR
    export NATIVE_FLAG_FILE EIGEN_NATIVE_FLAG EIGEN_REPS EIGEN_JOBS
    export EIGEN_OFFLINE_DIR PERF_EIGEN_ARCHIVE_URL PERF_EIGEN_MIRROR EIGEN_PROXY_PREFIX
    export EIGEN_ARCHIVE_NAME EIGEN_ARCHIVE_SHA256 EIGEN_ARCHIVE_URL
    export EIGEN_BTL_CONFIG EIGEN_BTL_NB_POINT EIGEN_BTL_MIN_TIME EIGEN_RUN_TIMEOUT
    export COMPILER_IDENTITY CMAKE_IDENTITY
}

initialize_runtime() {
    configure_runtime_paths || return $?
    mkdir -p "${RESULTS_DIR}" "${PERF_WORK_DIR}" "${TMPDIR}"
}

require_expected_arch_tools() {
    local missing=()
    local cmd
    for cmd in cmake c++ python3 tar sha256sum; do
        command -v "${cmd}" >/dev/null 2>&1 || missing+=("${cmd}")
    done
    if ((${#missing[@]})); then
        log_message "ERROR: missing required commands: ${missing[*]}"
        return 30
    fi
}
