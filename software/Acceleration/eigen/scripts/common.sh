# Upstream bench_gemm options: 5 tries of 10 inner repetitions per try keeps the
# timer resolution usable for the tiny matrix points; the driver reports its best
# try, which is exactly the throughput upstream prints.
EIGEN_GEMM_TRIES=5
EIGEN_GEMM_REPEATS=10

EIGEN_REPS="${PERF_REPS:-5}"
EIGEN_RUN_TIMEOUT="${PERF_EIGEN_RUN_TIMEOUT:-1800}"

# Lifecycle paths (assigned in configure_runtime_paths).
SOURCE_ARCHIVE=""
SOURCE_DIR=""
PROBE_DIR=""
SCRATCH_DIR=""
RUNS_DIR=""
COMPILER_IDENTITY="${COMPILER_IDENTITY:-}"

STANDALONE_OWNS_WORK_DIR="${STANDALONE_OWNS_WORK_DIR:-0}"
STANDALONE_KEEP_WORK_DIR="${STANDALONE_KEEP_WORK_DIR:-0}"
STANDALONE_STOP_DONE="${STANDALONE_STOP_DONE:-0}"
STANDALONE_CLEANUP_DONE="${STANDALONE_CLEANUP_DONE:-0}"

log_message() {
    printf '[eigen] [%s] %s\n' "$(TZ=UTC-8 date '+%F %T')" "$*"
}

normalize_architecture() {
    case "${1,,}" in
        x86_64|amd64) printf 'x86_64\n' ;;
        aarch64|arm64) printf 'aarch64\n' ;;
        *) printf '%s\n' "${1,,}" ;;
    esac
}

# Version string of the extracted upstream headers ("Eigen/Version").  This is
# the product's own version, not the requested one.
source_version_string() {
    local version_file="${SOURCE_DIR}/Eigen/Version"
    [[ -f "${version_file}" ]] || return 1
    sed -n 's/^#define EIGEN_VERSION_STRING "\(.*\)"$/\1/p' "${version_file}" | head -n 1
}

validate_variant() {
    case "${PERF_VARIANT}" in
        base|optimized) ;;
        *) log_message "ERROR: invalid build variant: ${PERF_VARIANT}"; return 10 ;;
    esac
}

validate_reps() {
    [[ "${EIGEN_REPS}" =~ ^[1-9][0-9]*$ ]] || {
        log_message "ERROR: PERF_REPS must be a positive integer, got ${EIGEN_REPS}"
        return 10
    }
    if ((EIGEN_REPS < 5)); then
        log_message "WARNING: PERF_REPS=${EIGEN_REPS} is a local link-validation value; formal evidence requires >= 5"
    fi
}

# The matrix points are passed to the parser as "m,k,n;m,k,n;..." because the
# parser lives on the host and must not parse bash arrays.
matrix_csv() {
    local first=1 triple
    for triple in "${EIGEN_GEMM_MATRIX[@]}"; do
        if ((first)); then
            first=0
        else
            printf ';'
        fi
        printf '%s' "${triple// /,}"
    done
    printf '\n'
}

matrix_point_count() {
    printf '%s\n' "${#EIGEN_GEMM_MATRIX[@]}"
}

matrix_slug() {
    printf 'm%s_k%s_n%s\n' "$1" "$2" "$3"
}

matrix_label() {
    printf '%s x %s * %s x %s\n' "$1" "$2" "$2" "$3"
}

# The upstream benchmark driver and the build/run self-check, both compiled
# inside the private container and therefore never present on the host.
gemm_binary_path() {
    printf '%s/gemm_bench\n' "${PROBE_DIR}"
}

probe_binary_path() {
    printf '%s/eigen_probe\n' "${PROBE_DIR}"
}

configure_runtime_paths() {
    validate_variant || return $?
    validate_reps || return $?
    if [[ -z "${PERF_RUN_ID}" ]]; then
        PERF_RUN_ID="local-$(date -u '+%Y%m%dT%H%M%SZ')-$$"
    fi
    if [[ ! "${PERF_RUN_ID}" =~ ^[A-Za-z0-9._-]+$ ]]; then
        log_message "ERROR: PERF_RUN_ID contains unsafe characters: ${PERF_RUN_ID}"
        return 10
    fi
    case "${EXPECTED_ARCH,,}" in
        x86_64|amd64) EXPECTED_ARCH="x86_64" ;;
        aarch64|arm64) EXPECTED_ARCH="aarch64" ;;
        *)
            log_message "ERROR: unsupported expected architecture: ${EXPECTED_ARCH}"
            return 20
            ;;
    esac
    local runner_architecture
    runner_architecture="$(normalize_architecture "$(uname -m)")"
    case "${runner_architecture}" in
        x86_64|aarch64) ;;
        *)
            log_message "ERROR: unsupported runner architecture: $(uname -m)"
            return 20
            ;;
    esac
    if [[ "${runner_architecture}" != "${EXPECTED_ARCH}" ]]; then
        log_message "ERROR: expected architecture ${EXPECTED_ARCH}, runner is ${runner_architecture}"
        return 20
    fi
    if [[ -z "${RESULTS_DIR}" ]]; then
        if [[ "${PERF_VARIANT}" == optimized ]]; then
            RESULTS_DIR="${SCRIPT_DIR}/results/${SOFTWARE_VERSION}/optimized/${PERF_RUN_ID}"
        else
            RESULTS_DIR="${SCRIPT_DIR}/results/${SOFTWARE_VERSION}/${PERF_RUN_ID}"
        fi
    fi
    if [[ -z "${PERF_WORK_DIR}" ]]; then
        PERF_WORK_DIR="/home/runner/boostkit-perf/eigen/local-${PERF_RUN_ID}"
        STANDALONE_OWNS_WORK_DIR=1
    fi
    TMPDIR="${PERF_WORK_DIR}/tmp"
    if [[ -z "${PERF_ACTUAL_VERSION_FILE}" ]]; then
        PERF_ACTUAL_VERSION_FILE="${RESULTS_DIR}/actual-version.txt"
    fi
    SOURCE_ARCHIVE="${PERF_WORK_DIR}/downloads/${EIGEN_ARCHIVE_NAME}"
    SOURCE_DIR="${PERF_WORK_DIR}/eigen-source"
    PROBE_DIR="${PERF_WORK_DIR}/probe"
    SCRATCH_DIR="${PERF_WORK_DIR}/scratch"
    RUNS_DIR="${RESULTS_DIR}/runs"
    export SOFTWARE_NAME SOFTWARE_VERSION EXPECTED_ARCH PERF_VARIANT PERF_RUN_ID
    export RESULTS_DIR PERF_WORK_DIR PERF_ACTUAL_VERSION_FILE TMPDIR
    export SOURCE_ARCHIVE SOURCE_DIR PROBE_DIR SCRATCH_DIR RUNS_DIR
    export EIGEN_REPS EIGEN_GEMM_TRIES EIGEN_GEMM_REPEATS EIGEN_RUN_TIMEOUT
    export EIGEN_OFFLINE_DIR PERF_EIGEN_ARCHIVE_URL PERF_EIGEN_MIRROR EIGEN_PROXY_PREFIX
    export EIGEN_ARCHIVE_NAME EIGEN_ARCHIVE_SHA256 EIGEN_ARCHIVE_URL
    export COMPILER_IDENTITY
}

initialize_runtime() {
    configure_runtime_paths || return $?
    mkdir -p "${RESULTS_DIR}" "${PERF_WORK_DIR}" "${TMPDIR}"
}

