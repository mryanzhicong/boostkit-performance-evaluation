#!/usr/bin/env bash
# Shared state and helpers for the Eigen Acceleration performance case.
#
# Eigen is a header-only C++ library, so the measured workload is the benchmark
# that ships inside the pinned upstream archive: bench/bench_gemm.cpp, Eigen's
# dense single-thread float matrix-matrix product benchmark.  See README.md for
# why that entry was chosen and why bench/spbench is not used.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOFTWARE_NAME="eigen"
SOFTWARE_VERSION="${SOFTWARE_VERSION:-5.0.1}"
EXPECTED_ARCH="${EXPECTED_ARCH:-$(uname -m)}"
PERF_VARIANT="${PERF_VARIANT:-base}"
PERF_RUN_ID="${PERF_RUN_ID:-}"
RESULTS_DIR="${RESULTS_DIR:-}"
PERF_WORK_DIR="${PERF_WORK_DIR:-}"
PERF_ACTUAL_VERSION_FILE="${PERF_ACTUAL_VERSION_FILE:-}"

# Upstream release artifact.  The archive is the tag archive generated by the
# upstream GitLab project; the digest below was computed from the downloaded
# file and is the only accepted input on every architecture and every mirror.
EIGEN_UPSTREAM_PROJECT="https://gitlab.com/libeigen/eigen"
EIGEN_RELEASE_BASE="${EIGEN_UPSTREAM_PROJECT}/-/archive"
EIGEN_ARCHIVE_NAME="eigen-${SOFTWARE_VERSION}.tar.gz"
EIGEN_ARCHIVE_SHA256="e9c326dc8c05cd1e044c71f30f1b2e34a6161a3b6ecf445d56b53ff1669e3dec"
EIGEN_ARCHIVE_URL="${EIGEN_RELEASE_BASE}/${SOFTWARE_VERSION}/${EIGEN_ARCHIVE_NAME}"

# Pre-placed offline mirrors are the preferred input; the directory is read-only
# for the case.  PERF_EIGEN_ARCHIVE_URL pins one complete URL and
# PERF_EIGEN_MIRROR prefixes the pinned archive name for restricted networks.
EIGEN_OFFLINE_DIR="${PERF_EIGEN_OFFLINE_DIR:-/home/runner/software/eigen}"
PERF_EIGEN_ARCHIVE_URL="${PERF_EIGEN_ARCHIVE_URL:-}"
PERF_EIGEN_MIRROR="${PERF_EIGEN_MIRROR:-}"
# Public forwarding proxy kept as a last resort for networks that cannot reach
# gitlab.com directly.  It must still return the byte-identical archive.
EIGEN_PROXY_PREFIX="${PERF_EIGEN_PROXY_PREFIX:-https://gh-proxy.com/}"

# The measured matrix: Eigen's dense single-thread float GEMM problems.  Each
# line is the tuple (m, k, n) of C(m x n) = A(m x k) * B(k x n); the upstream
# driver is invoked as ``bench_gemm -s <m> <n> <k>`` because its -s option takes
# rows, columns and depth in that order (see bench/bench_gemm.cpp).
EIGEN_GEMM_MATRIX=(
    "14 28 16"
    "16 8 4"
    "19 8 4"
    "1 16 16"
    "1 24 16"
    "32 16 8"
    "32 32 8"
    "32 8 4"
    "35 400 400"
    "35 800 1"
    "39 400 400"
    "39 492 1"
    "39 5 1"
    "39 800 1"
    "4130 104 32"
    "4130 116 32"
    "4130 16 1"
    "4130 32 16"
    "46 492 1"
    "46 5 1"
    "48 18 16"
    "50 100 1"
    "50 1298 250"
    "50 250 100"
    "50 250 250"
    "59 128 64"
    "59 1316 2"
    "59 1316 256"
    "59 1540 64"
    "59 1570 128"
    "59 1570 256"
    "59 16 8"
