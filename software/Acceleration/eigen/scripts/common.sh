# ==============================================================================
# Private openEuler container runtime
# ==============================================================================
# Every stage of this case runs inside a per-run openEuler 24.03 LTS SP4
# container.  The host keeps only Docker, download/verification tooling, the
# framework and the strict result parser; package installation, source
# extraction, builds, the measured process tree and cleanup happen inside the
# container.  The contract mirrors software/Database/mysql,
# software/Bigdata/ray and software/Others/unixbench.
#
# Generated by adaptation/scripts/add-container-block.py -- do not hand edit the
# region between the markers; change the template instead.
EIGEN_IMAGE_ARCHIVE_DIR="${EIGEN_IMAGE_ARCHIVE_DIR:-/home/runner/software/openEuler-24.03-LTS-SP4}"
EIGEN_CA_ANCHORS_DIR="${EIGEN_CA_ANCHORS_DIR:-/home/runner/software/anchors}"
EIGEN_CONTAINER_IMAGE="${EIGEN_CONTAINER_IMAGE:-}"
EIGEN_CONTAINER_NAME="${EIGEN_CONTAINER_NAME:-}"
EIGEN_CONTAINER_HOME="${EIGEN_CONTAINER_HOME:-}"
declare -p EIGEN_CONTAINER_EXTRA_ARGS >/dev/null 2>&1 || EIGEN_CONTAINER_EXTRA_ARGS=()

eigen_normalize_arch() {
    case "${1,,}" in
        x86_64|amd64) printf 'x86_64\n' ;;
        aarch64|arm64) printf 'aarch64\n' ;;
        *) printf '%s\n' "${1,,}" ;;
    esac
}

eigen_configure_container() {
    local arch
    arch="$(eigen_normalize_arch "${EXPECTED_ARCH:-$(uname -m)}")"
    [ -n "${EIGEN_CONTAINER_NAME}" ] || EIGEN_CONTAINER_NAME="boostkit-eigen-${arch}-${PERF_RUN_ID}"
    [ -n "${EIGEN_CONTAINER_HOME}" ] || EIGEN_CONTAINER_HOME="${PERF_WORK_DIR}/home"
    export EIGEN_CONTAINER_NAME EIGEN_CONTAINER_HOME
}

eigen_with_proxy() {
    if [ -n "${PERF_PROXY:-}" ]; then
        http_proxy="${PERF_PROXY}" https_proxy="${PERF_PROXY}" no_proxy="localhost,127.0.0.1,::1" "$@"
    else
        "$@"
    fi
}

require_eigen_docker() {
    if ! command -v docker >/dev/null 2>&1 || ! docker info >/dev/null 2>&1; then
        log_message 'ERROR: an accessible Docker daemon is required for the private container'
        return 30
    fi
}

verify_eigen_container_image_release() {
    local release
    release="$(docker run --rm --network=none "${EIGEN_CONTAINER_IMAGE}" cat /etc/os-release 2>/dev/null)" || {
        log_message 'ERROR: cannot read the loaded openEuler image release'
        return 30
    }
    case "${release}" in
        *'24.03'*) ;;
        *) log_message 'ERROR: loaded container image is not openEuler 24.03 LTS SP4'; return 30 ;;
    esac
}

prepare_eigen_container_image() {
    local arch archive_name archive checksum image_url load_output image_architecture
    arch="$(eigen_normalize_arch "${EXPECTED_ARCH}")"
    archive_name="openEuler-docker.${arch}.tar.xz"
    image_url="https://repo.openeuler.org/openEuler-24.03-LTS-SP4/docker_img/${arch}/${archive_name}"
    mkdir -p "${EIGEN_IMAGE_ARCHIVE_DIR}" "${PERF_WORK_DIR}" || return 30
    archive="${EIGEN_IMAGE_ARCHIVE_DIR}/${archive_name}"
    checksum="${archive}.sha256sum"
    if [ ! -s "${archive}" ]; then
        log_message "downloading openEuler container image archive: ${image_url}"
        archive="${PERF_WORK_DIR}/${archive_name}"
        eigen_with_proxy curl -fSL --retry 3 --connect-timeout 30 -o "${archive}.part" "${image_url}" || return 30
        mv -f "${archive}.part" "${archive}" || return 30
        eigen_with_proxy curl -fSL --retry 3 --connect-timeout 30 -o "${checksum}" "${image_url}.sha256sum" || return 30
    fi
    if [ -s "${checksum}" ]; then
        ( cd "$(dirname "${archive}")" && sha256sum -c "$(basename "${checksum}")" ) >/dev/null || {
            log_message "ERROR: container image checksum mismatch: ${archive}"
            return 30
        }
    else
        log_message "WARNING: no checksum file next to ${archive}; relying on the pinned path only"
    fi
    log_message "loading verified openEuler container image: ${archive}"
    load_output="$(docker load --input "${archive}")" || return 30
    EIGEN_CONTAINER_IMAGE="$(printf '%s\n' "${load_output}" | sed -nE 's/^Loaded image( ID)?: (.+)$/\2/p' | tail -n 1)"
    if [ -z "${EIGEN_CONTAINER_IMAGE}" ] || ! docker image inspect "${EIGEN_CONTAINER_IMAGE}" >/dev/null 2>&1; then
        log_message "ERROR: docker load did not report an inspectable image: ${load_output}"
        return 30
    fi
    image_architecture="$(docker image inspect --format '{{.Architecture}}' "${EIGEN_CONTAINER_IMAGE}")"
    case "${arch}:${image_architecture}" in
        x86_64:amd64|aarch64:arm64) ;;
        *)
            log_message "ERROR: loaded image architecture is ${image_architecture}, expected ${arch}"
            return 30
            ;;
    esac
    verify_eigen_container_image_release || return $?
    export EIGEN_CONTAINER_IMAGE
    log_message "openEuler container image is ready: ${EIGEN_CONTAINER_IMAGE} (${image_architecture})"
}

sweep_eigen_stale_containers() {
    local name label names
    command -v docker >/dev/null 2>&1 || return 0
    names="$(docker ps -a --filter "name=^boostkit-eigen-" --format '{{.Names}}' 2>/dev/null || true)"
    [ -n "${names}" ] || return 0
    while IFS= read -r name; do
        [ -n "${name}" ] || continue
        [ "${name}" = "${EIGEN_CONTAINER_NAME}" ] && continue
        label="$(docker inspect --format '{{index .Config.Labels "boostkit.eigen.run-id"}}' "${name}" 2>/dev/null || true)"
        [ -n "${label}" ] || continue
        [ "${label}" = "${PERF_RUN_ID}" ] && continue
        docker rm --force "${name}" >/dev/null 2>&1 || true
        log_message "removed stale container from an earlier run: ${name}"
    done <<< "${names}"
}

start_eigen_container() {
    local -a cert_mount=()
    local case_dir_mount_suffix=""
    eigen_configure_container
    require_eigen_docker || return $?
    if docker container inspect "${EIGEN_CONTAINER_NAME}" >/dev/null 2>&1; then
        log_message "ERROR: refusing to reuse an existing container: ${EIGEN_CONTAINER_NAME}"
        return 40
    fi
    sweep_eigen_stale_containers || true
    prepare_eigen_container_image || return $?
    # The case directory carries the benchmark sources and the timing harness, so
    # it is mounted read-only unless the standalone entry point keeps its results
    # inside the case directory.
    case "${RESULTS_DIR}" in
        "${SCRIPT_DIR}"/*) ;;
        *) case_dir_mount_suffix=",readonly" ;;
    esac
    if [ -n "${PERF_PROXY:-}" ]; then
        [ -d "${EIGEN_CA_ANCHORS_DIR}" ] || {
            log_message "ERROR: proxy CA directory is missing: ${EIGEN_CA_ANCHORS_DIR}"
            return 30
        }
        cert_mount+=(--mount "type=bind,source=${EIGEN_CA_ANCHORS_DIR},target=/etc/pki/ca-trust/source/anchors,readonly")
    fi
    mkdir -p "${EIGEN_CONTAINER_HOME}" || return 40
    log_message "starting private container ${EIGEN_CONTAINER_NAME} (host network, shared work and result directories)"
    docker run --detach --name "${EIGEN_CONTAINER_NAME}" \
        --label "boostkit.eigen.run-id=${PERF_RUN_ID}" \
        --network=host \
        --user "$(id -u):$(id -g)" \
        --ulimit nofile=1048576:1048576 \
        --mount "type=bind,source=${PERF_WORK_DIR},target=${PERF_WORK_DIR}" \
        --mount "type=bind,source=${RESULTS_DIR},target=${RESULTS_DIR}" \
        --mount "type=bind,source=${SCRIPT_DIR},target=${SCRIPT_DIR}${case_dir_mount_suffix}" \
        --mount type=bind,source=/etc/passwd,target=/etc/passwd,readonly \
        --mount type=bind,source=/etc/group,target=/etc/group,readonly \
        "${cert_mount[@]}" "${EIGEN_CONTAINER_EXTRA_ARGS[@]}" \
        "${EIGEN_CONTAINER_IMAGE}" sleep infinity >/dev/null || return 40
    if [ -n "${PERF_PROXY:-}" ]; then
        docker exec --user 0 "${EIGEN_CONTAINER_NAME}" update-ca-trust extract || {
            log_message 'ERROR: failed to update CA trust in the container'
            return 30
        }
    fi
    if docker exec --user 0 "${EIGEN_CONTAINER_NAME}" test -f /etc/yum.repos.d/openEuler.repo; then
        log_message 'switching private container repositories to the Huawei openEuler mirror'
        docker exec --user 0 "${EIGEN_CONTAINER_NAME}" sed -i \
            -e '/^meta/ s/^\(.*\)$/#\1/g' \
            -e 's/repo.openeuler.org/repo.huaweicloud.com\/openeuler/g' \
            /etc/yum.repos.d/openEuler.repo || {
            log_message 'ERROR: failed to switch the container repositories to the Huawei mirror'
            return 30
        }
    fi
    log_message "private container is running: ${EIGEN_CONTAINER_NAME}"
}

check_eigen_container() {
    eigen_configure_container
    [ "$(docker inspect --format '{{.State.Running}}' "${EIGEN_CONTAINER_NAME}" 2>/dev/null)" = "true" ] || {
        log_message "ERROR: managed container is not running: ${EIGEN_CONTAINER_NAME}"
        return 40
    }
}

eigen_docker_exec() {
    local workdir="$1" user="$2"
    shift 2
    eigen_configure_container
    local -a options=()
    local -a proxy=()
    [ -z "${PERF_PROXY:-}" ] || proxy=(-e "http_proxy=${PERF_PROXY}" -e "https_proxy=${PERF_PROXY}" -e 'no_proxy=localhost,127.0.0.1,::1')
    options+=("${proxy[@]}")
    options+=(-e "HOME=${EIGEN_CONTAINER_HOME}" -e "TMPDIR=${TMPDIR:-/tmp}" -e "PERF_RUN_ID=${PERF_RUN_ID}")
    [ -z "${workdir}" ] || options+=(--workdir "${workdir}")
    [ "${user}" != "root" ] || options+=(--user 0)
    docker exec "${options[@]}" "${EIGEN_CONTAINER_NAME}" "$@"
}

eigen_container_exec() { eigen_docker_exec '' '' "$@"; }

eigen_container_exec_at() {
    local workdir="$1"
    shift
    eigen_docker_exec "${workdir}" '' "$@"
}

eigen_container_exec_root() { eigen_docker_exec '' root "$@"; }

eigen_container_exec_root_at() {
    local workdir="$1"
    shift
    eigen_docker_exec "${workdir}" root "$@"
}

remove_eigen_container() {
    eigen_configure_container
    command -v docker >/dev/null 2>&1 || return 0
    docker container inspect "${EIGEN_CONTAINER_NAME}" >/dev/null 2>&1 || return 0
    if [ "$(docker inspect --format '{{index .Config.Labels "boostkit.eigen.run-id"}}' "${EIGEN_CONTAINER_NAME}" 2>/dev/null)" != "${PERF_RUN_ID}" ]; then
        log_message "ERROR: refusing to remove a container without this task's run-id label: ${EIGEN_CONTAINER_NAME}"
        return 60
    fi
    docker stop --time 30 "${EIGEN_CONTAINER_NAME}" >/dev/null || return 60
    docker rm "${EIGEN_CONTAINER_NAME}" >/dev/null || return 60
    log_message "removed managed container ${EIGEN_CONTAINER_NAME}"
}
