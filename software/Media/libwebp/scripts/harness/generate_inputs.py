#!/usr/bin/env python3
"""Generate the dashboard PNG inputs locally, without external media.

Ported line for line from the open-box task material
(``Test/libwebp/scripts/generate_inputs.py`` @ 21154155).  The generated bytes
are identical to the reference material: a 1920x1080 RGBA dashboard PNG plus a
1280x720 nearest-neighbour downscale of it, both written with
``zlib.compress(scan, 6)`` and the same chunk layout.

The only adaptation for this repository is that the output directory is an
explicit argument (the per-run container work directory) instead of the
hard-coded ``.work`` directory next to the reference script.
"""

from __future__ import annotations

import binascii
import hashlib
from pathlib import Path
import struct
import zlib


def digest(path):
    path = Path(path)
    result = hashlib.sha256()
    with path.open("rb") as stream:
        for data in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(data)
    return result.hexdigest()


def chunk(stream, kind, data):
    stream.write(struct.pack(">I", len(data)) + kind + data)
    stream.write(struct.pack(">I", binascii.crc32(kind + data) & 4294967295))


def generate_ui(path, transparent):
    w, h = (1920, 1080)
    raw = bytearray(w * h * 4)

    def rect(x, y, r, b, color):
        line = bytes(color) * (r - x)
        for row in range(y, b):
            raw[(row * w + x) * 4 : (row * w + r) * 4] = line

    rect(0, 0, w, h, (0, 0, 0, 0) if transparent else (238, 242, 248, 255))
    if not transparent:
        rect(0, 0, 240, h, (26, 39, 61, 255))
        rect(240, 0, w, 96, (255, 255, 255, 255))
    alpha = 220 if transparent else 255
    for i in range(3):
        x = 300 + i * 510
        rect(x + 8, 155, x + 478, 900, (18, 30, 48, 60 if transparent else 100))
        rect(x, 145, x + 470, 890, (255, 255, 255, alpha))
        rect(x + 28, 175, x + 230, 190, (43, 62, 83, alpha))
        rect(x + 28, 210, x + 150, 220, (135, 149, 166, alpha))
        for gy in range(300, 800, 100):
            rect(x + 30, gy, x + 440, gy + 2, (205, 215, 225, alpha))
        for j in range(10):
            size = 70 + (j * 71 + i * 47) % 330
            xx = x + 35 + j * 40
            rect(xx, 790 - size, xx + 24, 790, (36 + 45 * i, 112 + 12 * j, 210 - 35 * i, alpha))
        for k in range(5):
            rect(
                x + 30,
                820 + k * 10,
                x + 330 - k * 30,
                824 + k * 10,
                (92 + k * 12, 110 + k * 12, 130 + k * 12, alpha),
            )
    if not transparent:
        for j in range(10):
            rect(28, 140 + j * 70, 190 - j % 3 * 22, 154 + j * 70, (88, 112, 144, 255))
        for j in range(5):
            rect(290 + j * 280, 35, 460 + j * 280, 53, (80, 103, 128, 255))
    else:
        for y in range(80):
            rect(0, y, w, y + 1, (22, 34, 56, 20 + y * 2))
    with path.open("wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        chunk(f, b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
        scan = b"".join((b"\x00" + raw[y * w * 4 : (y + 1) * w * 4] for y in range(h)))
        chunk(f, b"IDAT", zlib.compress(scan, 6))
        chunk(f, b"IEND", b"")
    return hashlib.sha256(raw).hexdigest()


def resized_ui(source, target, width, height):
    data = source.read_bytes()
    offset = 8
    compressed = bytearray()
    while offset < len(data):
        length = struct.unpack(">I", data[offset : offset + 4])[0]
        if data[offset + 4 : offset + 8] == b"IDAT":
            compressed.extend(data[offset + 8 : offset + 8 + length])
        offset += length + 12
    rows = zlib.decompress(compressed)
    pixels = bytearray()
    for y in range(height):
        sy = y * 1080 // height
        line = rows[sy * (1920 * 4 + 1) + 1 : (sy + 1) * (1920 * 4 + 1)]
        pixels.extend(
            b"".join((line[x * 1920 // width * 4 : x * 1920 // width * 4 + 4] for x in range(width)))
        )
    with target.open("wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        chunk(f, b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        scan = b"".join((b"\x00" + pixels[y * width * 4 : (y + 1) * width * 4] for y in range(height)))
        chunk(f, b"IDAT", zlib.compress(scan, 6))
        chunk(f, b"IEND", b"")
    return hashlib.sha256(pixels).hexdigest()


def prepare_inputs(work_dir):
    """Write both dashboard PNGs under ``work_dir`` and describe them."""
    work = Path(work_dir)
    work.mkdir(parents=True, exist_ok=True)
    source = work / "dashboard.png"
    generate_ui(source, False)
    smaller = work / "dashboard_720p.png"
    resized_ui(source, smaller, 1280, 720)
    return [
        dict(name="dashboard_lossless_z0", path=source, width=1920, height=1080),
        dict(name="dashboard_720p_lossless_z0", path=smaller, width=1280, height=720),
    ]


if __name__ == "__main__":
    import sys

    directory = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    for image in prepare_inputs(directory):
        print(f"{image['name']}: {image['path']} ({digest(image['path'])})")
